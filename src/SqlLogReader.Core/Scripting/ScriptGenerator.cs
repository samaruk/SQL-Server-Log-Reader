using System.Text;
using SqlLogReader.Analysis;
using SqlLogReader.Decoding;
using SqlLogReader.Schema;

namespace SqlLogReader.Scripting;

public enum ScriptKind
{
    /// <summary>Re-applies the change (same effect as the original statement).</summary>
    Redo,
    /// <summary>Reverses the change (INSERT for a delete, DELETE for an insert, old values for an update).</summary>
    Undo,
}

/// <summary>Generates T-SQL that repeats or reverses decoded row changes.</summary>
public static class ScriptGenerator
{
    public static string Generate(RowChange change, ScriptKind kind) => (change.Operation, kind) switch
    {
        (ChangeOperation.Insert, ScriptKind.Redo) => Insert(change.Table, change.After),
        (ChangeOperation.Insert, ScriptKind.Undo) => Delete(change, preferBefore: false),
        (ChangeOperation.Delete, ScriptKind.Redo) => Delete(change, preferBefore: true),
        (ChangeOperation.Delete, ScriptKind.Undo) => Insert(change.Table, change.Before),
        (ChangeOperation.Update, ScriptKind.Redo) => Update(change, newValues: true),
        _ => Update(change, newValues: false),
    };

    /// <summary>
    /// A complete script for several changes. Undo scripts run in reverse log order so that
    /// later changes are reverted first.
    /// </summary>
    public static string GenerateScript(IEnumerable<RowChange> changes, ScriptKind kind, string? databaseName = null)
    {
        var list = changes.OrderBy(c => c.Lsn).ToList();
        if (kind == ScriptKind.Undo) list.Reverse();

        var sb = new StringBuilder();
        sb.AppendLine($"-- {kind} script generated by SQL Server Log Reader on {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine($"-- {list.Count} change(s). Review before running.");
        if (databaseName != null)
            sb.AppendLine($"USE {TableInfo.Quote(databaseName)};");
        sb.AppendLine("SET XACT_ABORT ON;");
        sb.AppendLine("BEGIN TRANSACTION;");
        sb.AppendLine();
        foreach (var change in list)
        {
            sb.AppendLine($"-- {change.Lsn} {change.Operation} {change.TableName} (transaction {change.Transaction.TransactionId}" +
                          (change.Time.HasValue ? $", {change.Time:yyyy-MM-dd HH:mm:ss}" : "") +
                          (string.IsNullOrEmpty(change.UserName) ? "" : $", {change.UserName}") + ")");
            sb.AppendLine(Generate(change, kind));
            sb.AppendLine();
        }
        sb.AppendLine("COMMIT TRANSACTION;");
        return sb.ToString();
    }

    private static string Insert(TableInfo table, DecodedRow? row)
    {
        if (row == null) return "-- Cannot generate INSERT: the row image is not available.";
        var columns = row.Values.Where(v => IsInsertable(v.Column)).ToList();
        var sb = new StringBuilder();
        var warnings = columns.Where(v => !v.HasValue).Select(v => $"{v.Name} ({v.Note ?? v.State.ToString()})").ToList();
        if (warnings.Count > 0)
            sb.AppendLine($"-- WARNING: value(s) not recoverable from the log, written as NULL: {string.Join(", ", warnings)}");

        bool identity = columns.Any(v => v.Column.IsIdentity);
        if (identity) sb.AppendLine($"SET IDENTITY_INSERT {table.QualifiedName} ON;");
        sb.Append($"INSERT INTO {table.QualifiedName} (");
        sb.Append(string.Join(", ", columns.Select(v => TableInfo.Quote(v.Name))));
        sb.Append(") VALUES (");
        sb.Append(string.Join(", ", columns.Select(v => SqlLiteral.TryFormat(v) ?? "NULL")));
        sb.Append(");");
        if (identity) sb.AppendLine().Append($"SET IDENTITY_INSERT {table.QualifiedName} OFF;");
        return sb.ToString();
    }

    private static string Delete(RowChange change, bool preferBefore)
    {
        var where = Where(change, preferBefore, out bool unique);
        if (where == null) return "-- Cannot generate DELETE: the row cannot be identified from the log.";
        var top = unique ? "" : "TOP (1) ";
        return $"DELETE {top}FROM {change.Table.QualifiedName} WHERE {where};";
    }

    private static string Update(RowChange change, bool newValues)
    {
        var changed = change.ChangedColumns.ToList();
        if (changed.Count == 0) return "-- No changed column could be decoded for this update.";

        var assignments = new List<string>();
        var missing = new List<string>();
        foreach (var c in changed)
        {
            var value = newValues ? c.After : c.Before;
            var literal = value == null ? null : SqlLiteral.TryFormat(value);
            if (literal == null || c.Column.IsComputed || c.Column.SystemType == SqlSystemType.Timestamp)
            {
                if (!c.Column.IsComputed && c.Column.SystemType != SqlSystemType.Timestamp) missing.Add(c.Name);
                continue;
            }
            assignments.Add($"{TableInfo.Quote(c.Name)} = {literal}");
        }

        // Find the row as it is before this script runs: redo -> old values, undo -> new values.
        var where = Where(change, preferBefore: newValues, out bool unique);
        var sb = new StringBuilder();
        if (missing.Count > 0)
            sb.AppendLine($"-- WARNING: changed column(s) whose value is not in the log were skipped: {string.Join(", ", missing)}");
        if (assignments.Count == 0) return sb.Append("-- Nothing to update.").ToString();
        if (where == null) return sb.Append("-- Cannot generate UPDATE: the row cannot be identified from the log.").ToString();
        var top = unique ? "" : "TOP (1) ";
        sb.Append($"UPDATE {top}{change.Table.QualifiedName} SET {string.Join(", ", assignments)} WHERE {where};");
        return sb.ToString();
    }

    private static string? Where(RowChange change, bool preferBefore, out bool unique)
    {
        unique = false;
        var id = RowIdentification.For(change, preferBefore);
        if (id == null) return null;
        var predicates = new List<string>();
        foreach (var v in id.Values)
        {
            var literal = SqlLiteral.TryFormat(v);
            if (literal == null) continue;
            predicates.Add(v.IsNull ? $"{TableInfo.Quote(v.Name)} IS NULL" : $"{TableInfo.Quote(v.Name)} = {literal}");
        }
        if (predicates.Count == 0) return null;
        unique = id.IsUnique;
        return string.Join(" AND ", predicates);
    }

    private static bool IsInsertable(ColumnInfo column) =>
        !column.IsComputed && column.SystemType != SqlSystemType.Timestamp;
}
